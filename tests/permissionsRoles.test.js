import test from 'node:test'
import assert from 'node:assert/strict'
import { getRolePermissions } from '../src/permissions/roles.js'

test('maps university and examination roles to the expected permissions', () => {
  const universityAdminPermissions = getRolePermissions('university_administrator')
  const examOfficerPermissions = getRolePermissions('examination_officer')
  const staffPermissions = getRolePermissions('staff')

  assert.ok(universityAdminPermissions.includes('student:view'))
  assert.ok(universityAdminPermissions.includes('student:create'))
  assert.ok(universityAdminPermissions.includes('staff:create'))
  assert.ok(universityAdminPermissions.includes('course:create'))
  assert.ok(universityAdminPermissions.includes('report:view'))
  assert.ok(universityAdminPermissions.includes('notification:view'))
  assert.ok(universityAdminPermissions.includes('settings:view'))
  assert.ok(universityAdminPermissions.includes('department:view'))
  assert.ok(universityAdminPermissions.includes('faculty:view'))
  assert.ok(universityAdminPermissions.includes('profile:view'))
  assert.ok(!universityAdminPermissions.includes('system:view'))
  assert.ok(!universityAdminPermissions.includes('user:manage'))
  assert.ok(!universityAdminPermissions.includes('university:create'))
  assert.ok(universityAdminPermissions.includes('result:view'))
  assert.ok(!universityAdminPermissions.includes('result:approve'))

  const superAdminPermissions = getRolePermissions('super_admin')
  assert.ok(superAdminPermissions.includes('system:view'))
  assert.ok(superAdminPermissions.includes('system:manage'))
  assert.ok(superAdminPermissions.includes('user:manage'))
  assert.ok(!superAdminPermissions.includes('student:view'))
  assert.ok(!superAdminPermissions.includes('course:create'))
  assert.ok(!superAdminPermissions.includes('result:view'))
  assert.ok(!superAdminPermissions.includes('staff:view'))

  const adminPermissions = getRolePermissions('admin')
  assert.ok(adminPermissions.includes('system:view'))
  assert.ok(adminPermissions.includes('system:manage'))
  assert.ok(adminPermissions.includes('user:manage'))
  assert.ok(!adminPermissions.includes('student:view'))
  assert.ok(!adminPermissions.includes('course:create'))
  assert.ok(!adminPermissions.includes('result:view'))
  assert.ok(!adminPermissions.includes('staff:view'))

  assert.ok(examOfficerPermissions.includes('exams:manage'))
  assert.ok(examOfficerPermissions.includes('result:review'))
  assert.ok(examOfficerPermissions.includes('result:view'))

  const deanPermissions = getRolePermissions('dean')
  assert.ok(deanPermissions.includes('faculty:view'))
  assert.ok(deanPermissions.includes('result:review'))
  assert.ok(deanPermissions.includes('result:view'))
  assert.ok(deanPermissions.includes('result:approve'))
  assert.ok(deanPermissions.includes('dean:view'))
  assert.ok(deanPermissions.includes('report:view'))
  assert.ok(!deanPermissions.includes('result:create'))
  assert.ok(!deanPermissions.includes('course:create'))

  const hodPermissions = getRolePermissions('hod')
  assert.ok(hodPermissions.includes('result:view'))
  assert.ok(hodPermissions.includes('result:approve'))
  assert.ok(hodPermissions.includes('hod:view'))
  assert.ok(hodPermissions.includes('report:view'))
  assert.ok(hodPermissions.includes('profile:view'))
  assert.ok(!hodPermissions.includes('result:create'))
  assert.ok(!hodPermissions.includes('student:create'))
  assert.ok(!hodPermissions.includes('staff:create'))
  assert.ok(!hodPermissions.includes('course:create'))

  const lecturerPermissions = getRolePermissions('lecturer')
  assert.ok(lecturerPermissions.includes('result:create'))
  assert.ok(lecturerPermissions.includes('student:view'))
  assert.ok(lecturerPermissions.includes('result:view'))
  assert.ok(lecturerPermissions.includes('assessment:view'))
  assert.ok(lecturerPermissions.includes('lecturer:view'))
  assert.ok(lecturerPermissions.includes('profile:view'))
  assert.ok(!lecturerPermissions.includes('result:approve'))

  const studentPermissions = getRolePermissions('student')
  assert.ok(studentPermissions.includes('student:portal:view'))
  assert.ok(studentPermissions.includes('profile:view'))
  assert.ok(studentPermissions.includes('result:view'))
  assert.ok(studentPermissions.includes('registration:view'))
  assert.ok(studentPermissions.includes('notification:view'))
  assert.ok(studentPermissions.includes('documents:view'))
  assert.ok(!studentPermissions.includes('result:approve'))
  assert.ok(!studentPermissions.includes('course:create'))
  assert.ok(!studentPermissions.includes('staff:create'))
  assert.ok(!lecturerPermissions.includes('system:view'))
  assert.ok(!lecturerPermissions.includes('user:manage'))
  assert.ok(!lecturerPermissions.includes('course:create'))
  assert.ok(!lecturerPermissions.includes('student:create'))
  assert.ok(!lecturerPermissions.includes('staff:create'))
  assert.ok(!deanPermissions.includes('staff:create'))
  assert.ok(!deanPermissions.includes('student:create'))
  assert.ok(!deanPermissions.includes('university:create'))
  assert.ok(!deanPermissions.includes('system:view'))
  assert.ok(!deanPermissions.includes('user:manage'))
})
